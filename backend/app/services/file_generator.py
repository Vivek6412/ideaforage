def gen_schema_md(blueprint: dict[str, Any]) -> str:
    db_schema = blueprint.get("database_schema", {})
    tables = db_schema.get("tables", [])
    sql_blocks: list[str] = []

    for table in tables:
        if not isinstance(table, dict):
            continue
        table_name = table.get("name", "unknown_table")
        fields = table.get("fields", [])
        indexes = table.get("indexes", [])
        notes = table.get("notes", "")

        field_lines: list[str] = []
        for field in fields:
            if not isinstance(field, dict):
                continue
            col_name = field.get("name", "")
            col_type = field.get("type", "TEXT")
            constraints = field.get("constraints", [])
            constraint_str = " ".join(constraints) if constraints else ""
            field_lines.append(f"  {col_name} {col_type} {constraint_str}".rstrip())

        rel_lines = []
        for rel in table.get("relationships", []):
            if isinstance(rel, str):
                rel_lines.append(f"  -- Relationship: {rel}")

        body = ",\n".join(field_lines)
        sql = f"CREATE TABLE {table_name} (\n{body}\n);"
        if notes:
            sql = f"-- {notes}\n{sql}"
        sql_blocks.append(sql)

        for idx in indexes:
            if isinstance(idx, str):
                sql_blocks.append(
                    f"CREATE INDEX {idx} ON {table_name} ({idx.split('_', 2)[-1]});"
                )

    if not sql_blocks:
        sql_blocks = [
            "-- Database schema will be generated from blueprint modules.\n"
            "-- Ensure UUID PKs, TIMESTAMPTZ timestamps, soft deletes where needed."
        ]

    return "# SCHEMA.md\n# Implement exactly as written. No deviations.\n\n" + "\n\n".join(sql_blocks)


def gen_api_spec_md(blueprint: dict[str, Any]) -> str:
    endpoints = blueprint.get("api_endpoints", [])
    tech_stack = blueprint.get("tech_stack", {})
    be_tech = tech_stack.get("backend", {}).get("tech", "FastAPI")

    lines: list[str] = [
        "# API_SPEC.md\n# IMPLEMENT ALL ENDPOINTS. EXACT ROUTES. EXACT METHODS.\n",
        f"Base URL: /api/v1\n"
        f"Backend:  {be_tech}\n"
        "Auth:     JWT via httpOnly cookie named 'access_token'\n",
        "---\n",
    ]

    # Group endpoints by prefix
    groups: dict[str, list[dict[str, Any]]] = {}
    for ep in endpoints:
        if not isinstance(ep, dict):
            continue
        route = ep.get("path", "")
        parts = route.strip("/").split("/")
        # Group by first meaningful segment after "api/v1"
        idx = next(
            (i for i, p in enumerate(parts) if p not in ("api", "v1")),
            len(parts) - 1,
        )
        group = parts[idx] if idx < len(parts) else "misc"
        groups.setdefault(group.upper(), []).append(ep)

    for group_name, group_eps in groups.items():
        lines.append(f"## {group_name}")
        for ep in group_eps:
            method = ep.get("method", "GET").upper()
            route = ep.get("path", "")
            desc = ep.get("description", "")
            auth = ep.get("auth_required", True)
            auth_str = "Required" if auth else "None"
            body = ep.get("body", {})
            returns = ep.get("returns", {})

            ep_block = f"{method:8} {route}\n  Auth:    {auth_str}\n  Desc:    {desc}"
            if body:
                ep_block += f"\n  Body:    {json.dumps(body, separators=(',', ':'))}"
            if returns:
                ep_block += f"\n  Returns: {json.dumps(returns, separators=(',', ':'))}"
            lines.append(ep_block)
        lines.append("")

    if not groups:
        lines.append(
            "Endpoints will be defined per module. Follow this pattern:\n"
            "  GET    /api/v1/{resource}           → list\n"
            "  POST   /api/v1/{resource}           → create\n"
            "  GET    /api/v1/{resource}/{id}      → detail\n"
            "  PATCH  /api/v1/{resource}/{id}      → update\n"
            "  DELETE /api/v1/{resource}/{id}      → delete\n"
        )

    return "\n".join(lines)


def gen_business_logic_md(blueprint: dict[str, Any], idea: dict[str, Any]) -> str:
    modules = blueprint.get("modules", [])
    complexity = blueprint.get("complexity_estimate", "Medium")
    cuts = blueprint.get("module_cut_suggestions", [])

    module_rules: list[str] = []
    for m in modules:
        if not isinstance(m, dict):
            continue
        name = m.get("name", "")
        desc = m.get("description", "")
        deps = m.get("depends_on", [])
        dep_str = f"Depends on: {', '.join(deps)}" if deps else "No dependencies"
        module_rules.append(
            f"### {name}\n{desc}\n{dep_str}"
        )

    cuts_block = "\n".join(f"- {c}" for c in cuts) if cuts else "None"
    features = idea.get("core_features", [])
    feature_block = "\n".join(f"- {f}" for f in features) if features else "See modules"

    return f"""# BUSINESS_LOGIC.md

## Complexity
{complexity}

## Core Features to Implement
{feature_block}

## Module Rules
{chr(10).join(module_rules) or "Build modules in dependency order as defined in MASTER.md"}

## General Rules
- Sequential operations: validate input → process → persist → respond
- Never trust user input: validate heavily on every endpoint
- Never expose internal errors to client: catch exceptions, return proper HTTP codes
- State transitions: only valid transitions allowed (enforce in service layer)
- Ownership: always verify resource belongs to authenticated user
- Idempotent writes: upsert where possible (avoid duplicate key errors)

## State Transitions (only these are valid)
```
DRAFT → PENDING (trigger: user submission)
PENDING → APPROVED (trigger: admin review)
PENDING → REJECTED (trigger: admin review)
APPROVED → ACTIVE (trigger: system process)
ACTIVE → ARCHIVED (trigger: user action)
```

## Error Classification
```json
{{
    "missing_dependency": "ModuleNotFoundError|ImportError",
    "auth_error": "401|Unauthorized|JWT",
    "syntax_error": "SyntaxError|unexpected token"
}}
```

## API Contract Rules
- All routes versioned: /api/v1/
- All responses use consistent error format: {{ detail, code, field }}
- Auth: read user_id from JWT token only — never from request body
- Pagination: cursor-based for large collections
- File uploads: validate MIME type and size before processing

## Module Cut Suggestions (High complexity only)
{cuts_block}
"""


