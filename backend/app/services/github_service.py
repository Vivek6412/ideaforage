# Files/patterns that must never be pushed (BUSINESS_LOGIC Stage 5)
EXCLUDED_PATTERNS: list[str] = [
    ".env",
    "__pycache__",
    "node_modules",
    ".next",
    ".pyc",
    "venv/",
    ".DS_Store",
]


# ── Exclusion filter ──────────────────────────────────────────────────────────

def _is_excluded(path: str) -> bool:
    """Return True if the file path matches any exclusion pattern."""
    for pattern in EXCLUDED_PATTERNS:
        if pattern.startswith(".") and not pattern.startswith(".env"):
            # Extension match (e.g. .pyc)
            if path.endswith(pattern):
                return True
        if pattern in path:
            return True
    # Never push bare .env (matches .env exactly or .env at path boundary)
    basename = os.path.basename(path)
    if basename == ".env":
        return True
    return False


# ── OAuth ─────────────────────────────────────────────────────────────────────

def get_oauth_url() -> str:
    """Build GitHub OAuth URL with repo scope."""
    params = (
        f"client_id={settings.GITHUB_CLIENT_ID}"
        f"&redirect_uri={settings.GITHUB_REDIRECT_URI}"
        f"&scope=repo"
    )
    return f"{GITHUB_OAUTH_URL}?{params}"


async def exchange_code_for_token(code: str) -> str:
    """POST to GitHub, return raw access_token string."""
    async with httpx.AsyncClient(timeout=15.0) as client:
        resp = await client.post(
            GITHUB_TOKEN_URL,
            headers={"Accept": "application/json"},
            data={
                "client_id": settings.GITHUB_CLIENT_ID,
                "client_secret": settings.GITHUB_CLIENT_SECRET,
                "code": code,
            },
        )
    resp.raise_for_status()
    data = resp.json()
    token = data.get("access_token")
    if not token:
        error = data.get("error_description", data.get("error", "unknown"))
        raise ValueError(f"GitHub token exchange failed: {error}")
    return token


async def get_github_username(token: str) -> str:
    """GET /user, return login username."""
    async with httpx.AsyncClient(timeout=10.0) as client:
        resp = await client.get(
            f"{GITHUB_API_URL}/user",
            headers={
                "Authorization": f"Bearer {token}",
                "Accept": "application/vnd.github+json",
            },
        )
    resp.raise_for_status()
    return resp.json()["login"]


