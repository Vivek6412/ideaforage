def gen_stack_md(blueprint: dict[str, Any]) -> str:
    tech_stack = blueprint.get("tech_stack", {})
    sections: list[str] = ["# STACK.md\n# EXACT VERSIONS. NO ALTERNATIVES. NO DEVIATIONS.\n"]

    for layer, info in tech_stack.items():
        if layer == "deployment":
            continue
        if isinstance(info, dict):
            tech = info.get("tech", layer.capitalize())
            version = info.get("version", "latest")
            reasoning = info.get("reasoning", "")
            sections.append(
                f"## {layer.capitalize()}\n"
                f"Tech:       {tech} {version}\n"
                f"Reasoning:  {reasoning}\n"
            )

    deploy = tech_stack.get("deployment", {})
    if isinstance(deploy, dict):
        fe_host = deploy.get("frontend", "")
        be_host = deploy.get("backend", "")
        if fe_host or be_host:
            sections.append(
                f"## Deployment\n"
                f"Frontend:   {fe_host}\n"
                f"Backend:    {be_host}\n"
            )

    return "\n".join(sections)


