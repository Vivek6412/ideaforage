def gen_dependencies_md(blueprint: dict[str, Any]) -> str:
    bp_deps = blueprint.get("dependencies", {})
    py_deps = bp_deps.get("python", [])
    npm_deps = bp_deps.get("npm", [])

    pip_lines: list[str] = []
    pip_install_parts: list[str] = []

    for dep in py_deps:
        if isinstance(dep, dict):
            name = dep.get("name", "")
            version = dep.get("version", "")
            purpose = dep.get("purpose", "")
            if name:
                spec = f"{name}=={version}" if version and version != "latest" else name
                pip_lines.append(f"{spec:<40} # {purpose}" if purpose else spec)
                pip_install_parts.append(spec)
        elif isinstance(dep, str):
            pip_lines.append(dep)
            pip_install_parts.append(dep)

    npm_lines: list[str] = []
    npm_install_parts: list[str] = []

    for dep in npm_deps:
        if isinstance(dep, dict):
            name = dep.get("name", "")
            version = dep.get("version", "")
            purpose = dep.get("purpose", "")
            if name:
                spec = f"{name}@{version}" if version and version != "latest" else name
                npm_lines.append(f"{spec:<50} # {purpose}" if purpose else spec)
                npm_install_parts.append(spec)
        elif isinstance(dep, str):
            npm_lines.append(dep)
            npm_install_parts.append(dep)

    pip_block = "\n".join(pip_lines) if pip_lines else "# (defined by blueprint tech_stack)"
    npm_block = "\n".join(npm_lines) if npm_lines else "# (defined by blueprint tech_stack)"
    pip_cmd = f"pip install {' '.join(pip_install_parts)}" if pip_install_parts else "pip install -r requirements.txt"
    npm_cmd = f"npm install {' '.join(npm_install_parts)}" if npm_install_parts else "npm install"

    return f"""# DEPENDENCIES.md
# EXACT VERSIONS. Install exactly as shown. Never substitute.

## Python Packages (backend/)
```bash
{pip_cmd}
```

{pip_block}

## npm Packages (frontend/)
```bash
{npm_cmd}
```

{npm_block}
"""


def generate_file_injection_guide(blueprint: dict[str, Any]) -> str:
    modules = blueprint.get("modules", [])
    sections: list[str] = [
        "# FILE_INJECTION_GUIDE.md",
        "## Module-to-File Injection Map\n",
    ]

    for m in modules:
        if not isinstance(m, dict):
            continue
        name = m.get("name", "Module")
        deps = m.get("depends_on", [])
        sections.append(f"### {name}")
        sections.append(f"Primary files to inject for building this module:")
        
        snake_name = name.lower().replace(" ", "_")
        sections.append(f"- backend/app/models/{snake_name}.py")
        sections.append(f"- backend/app/schemas/{snake_name}.py")
        sections.append(f"- backend/app/services/{snake_name}_service.py")
        sections.append(f"- backend/app/routers/{snake_name}.py")
        sections.append(f"- frontend/app/dashboard/{snake_name.replace('_', '-')}/page.tsx")
        
        if deps:
            sections.append(f"\nRequires context from modules: {', '.join(deps)}")
        sections.append("")

    return "\n".join(sections)


async def upload_to_storage(project_id: UUID, files: dict[str, str]) -> list[dict[str, Any]]:
    """Upload all files to Supabase Storage."""
    results = []
    
    supabase_url = settings.SUPABASE_URL
    service_key = settings.SUPABASE_SERVICE_KEY
    bucket = settings.SUPABASE_STORAGE_BUCKET

    async with httpx.AsyncClient(timeout=30.0) as client:
        for filename, content in files.items():
            path = f"{project_id}/{filename}"
            upload_url = f"{supabase_url}/storage/v1/object/{bucket}/{path}"
            
            try:
                resp = await client.post(
                    upload_url,
                    headers={
                        "Authorization": f"Bearer {service_key}",
                        "Content-Type": "text/plain; charset=utf-8",
                        "x-upsert": "true",
                    },
                    content=content.encode("utf-8")
                )
                
                if resp.status_code in (200, 201):
                    results.append({
                        "name": filename,
                        "url": f"{supabase_url}/storage/v1/object/public/{bucket}/{path}",
                        "size": len(content)
                    })
                else:
                    logger.error("Failed to upload %s: %s", filename, resp.text)
            except Exception as e:
                logger.error("Error uploading %s: %s", filename, e)

    return results
