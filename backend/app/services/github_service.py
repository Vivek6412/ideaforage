# ── File collection ───────────────────────────────────────────────────────────

async def _collect_approved_files(
    db: AsyncSession,
    project_id: UUID,
) -> list[dict[str, str]]:
    """Collect generated_files from all approved execution tasks."""
    result = await db.execute(
        select(ExecutionTask).where(
            ExecutionTask.project_id == project_id,
            ExecutionTask.status == "approved",
        )
    )
    tasks = list(result.scalars().all())
    files: list[dict[str, str]] = []
    for task in tasks:
        for f in task.generated_files or []:
            path = f.get("path", "")
            if path and not _is_excluded(path):
                files.append({"path": path, "content": f.get("content", "")})
    return files


def _build_file_tree(
    project: Project,
    approved_files: list[dict[str, str]],
) -> list[dict[str, str]]:
    """Merge approved files with auto-generated files; apply exclusion filter."""
    auto: list[dict[str, str]] = [
        {"path": "README.md",      "content": generate_readme(project)},
        {"path": ".gitignore",     "content": generate_gitignore()},
        {"path": ".env.example",   "content": generate_env_example(project)},
        {"path": "LICENSE",        "content": MIT_LICENSE.format(year=datetime.now().year)},
    ]
    # approved files may already contain README etc — auto-generated wins
    auto_paths = {f["path"] for f in auto}
    filtered_approved = [f for f in approved_files if f["path"] not in auto_paths]
    return auto + filtered_approved


# ── GitHub repo push ──────────────────────────────────────────────────────────

async def get_preview(
    db: AsyncSession,
    project_id: UUID,
    user_id: UUID,
) -> dict[str, Any]:
    """Return file list that would be pushed, without actually pushing."""
    project = await _get_project(db, project_id, user_id)
    approved = await _collect_approved_files(db, project_id)
    all_files = _build_file_tree(project, approved)
    auto_paths = ["README.md", ".gitignore", ".env.example", "LICENSE"]
    return {
        "files": [f["path"] for f in all_files],
        "auto_generated": auto_paths,
        "total": len(all_files),
    }


async def push_to_github(
    db: AsyncSession,
    project: Project,
    repo_name: str,
    is_private: bool,
    branch: str,
    github_token: str,
) -> dict[str, str]:
    """
    1. Collect approved files + auto-generated.
    2. Filter excluded.
    3. Create GitHub repo via PyGitHub.
    4. Single commit all files.
    5. Return { repo_url, commit_sha }.
    """
    import asyncio

    approved = await _collect_approved_files(db, project.id)
    all_files = _build_file_tree(project, approved)

    def _do_push() -> dict[str, str]:
        gh = Github(github_token)
        user = gh.get_user()

        # Create repo
        try:
            repo = user.create_repo(
                name=repo_name,
                private=is_private,
                auto_init=False,
                description=f"Generated by IdeaForge AI — {getattr(project, 'name', repo_name)}",
            )
        except GithubException as exc:
            raise ValueError(f"Repo creation failed: {exc.data.get('message', exc)}") from exc

        # Build git tree elements for a single commit
        blobs = []
        for f in all_files:
            content = f["content"]
            try:
                blob = repo.create_git_blob(content, "utf-8")
            except GithubException:
                # Binary fallback — encode as base64
                encoded = base64.b64encode(content.encode()).decode()
                blob = repo.create_git_blob(encoded, "base64")
            blobs.append(
                {
                    "path": f["path"],
                    "mode": "100644",
                    "type": "blob",
                    "sha": blob.sha,
                }
            )

        # Create tree → commit → update ref
        tree = repo.create_git_tree(blobs)
        parent_commits: list[Any] = []  # empty = root commit

        commit = repo.create_git_commit(
            message=COMMIT_MESSAGE,
            tree=tree,
            parents=parent_commits,
        )

        # Create branch ref
        try:
            repo.create_git_ref(f"refs/heads/{branch}", commit.sha)
        except GithubException as exc:
            raise ValueError(f"Branch ref creation failed: {exc.data.get('message', exc)}") from exc

        return {"repo_url": repo.html_url, "commit_sha": commit.sha}

    # PyGitHub is sync → run in thread pool to avoid blocking event loop
    result = await asyncio.to_thread(_do_push)
    return result


# ── DB helpers ────────────────────────────────────────────────────────────────

async def _get_project(
    db: AsyncSession,
    project_id: UUID,
    user_id: UUID,
) -> Project:
    from fastapi import HTTPException

    result = await db.execute(
        select(Project).where(
            Project.id == project_id,
            Project.user_id == user_id,
        )
    )
    project = result.scalar_one_or_none()
    if not project:
        raise HTTPException(
            status_code=404,
            detail={"detail": "Project not found", "code": "PROJECT_NOT_FOUND"},
        )
    return project


async def _get_integration(
    db: AsyncSession,
    user_id: UUID,
    provider: str,
) -> UserIntegration | None:
    result = await db.execute(
        select(UserIntegration).where(
            UserIntegration.user_id == user_id,
            UserIntegration.provider == provider,
        )
    )
    return result.scalar_one_or_none()


async def save_push_result(
    db: AsyncSession,
    project_id: UUID,
    repo_name: str,
    branch: str,
    is_private: bool,
    result: dict[str, str],
) -> GithubPush:
    record = GithubPush(
        project_id=project_id,
        repo_url=result["repo_url"],
        repo_name=repo_name,
        branch=branch,
        is_private=is_private,
        commit_sha=result["commit_sha"],
        status="success",
        pushed_at=datetime.now(timezone.utc),
    )
    db.add(record)
    await db.commit()
    await db.refresh(record)
    return record


async def advance_state_to_pushed(
    db: AsyncSession,
    project_id: UUID,
    user_id: UUID,
) -> None:
    project = await _get_project(db, project_id, user_id)
    advance_state(project, "GITHUB_PUSHED")
    await db.commit()


# ── Integration store/retrieve helpers ───────────────────────────────────────

async def store_integration(
    db: AsyncSession,
    user_id: UUID,
    provider: str,
    access_token: str,
    username: str,
) -> UserIntegration:
    """Upsert encrypted integration token."""
    encrypted = encrypt(access_token)
    existing = await _get_integration(db, user_id, provider)
    if existing:
        existing.access_token = encrypted
        existing.username = username
        await db.commit()
        await db.refresh(existing)
        return existing
    record = UserIntegration(
        user_id=user_id,
        provider=provider,
        access_token=encrypted,
        username=username,
    )
    db.add(record)
    await db.commit()
    await db.refresh(record)
    return record


async def get_decrypted_token(
    db: AsyncSession,
    user_id: UUID,
    provider: str,
) -> str | None:
    """Return decrypted access token or None if not connected."""
    integration = await _get_integration(db, user_id, provider)
    if not integration:
        return None
    try:
        return decrypt(integration.access_token)
    except Exception:
        logger.warning("Fernet decryption failed for user=%s provider=%s", user_id, provider)
        return None


async def list_integrations(
    db: AsyncSession,
    user_id: UUID,
) -> list[dict[str, Any]]:
    """Return connection status for all known providers."""
    result = await db.execute(
        select(UserIntegration).where(UserIntegration.user_id == user_id)
    )
    rows = {r.provider: r for r in result.scalars().all()}
    providers = ["github", "vercel", "railway"]
    return [
        {
            "provider": p,
            "connected": p in rows,
            "username": rows[p].username if p in rows else None,
        }
        for p in providers
    ]


async def delete_integration(
    db: AsyncSession,
    user_id: UUID,
    provider: str,
) -> None:
    from fastapi import HTTPException

    integration = await _get_integration(db, user_id, provider)
    if not integration:
        raise HTTPException(
            status_code=404,
            detail={"detail": f"No {provider} integration found", "code": "INTEGRATION_NOT_FOUND"},
        )
    await db.delete(integration)
    await db.commit()